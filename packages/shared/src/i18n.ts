export function translate(language: Language, key: TranslationKey): string {
  return (language === 'ar' ? ar : en)[key];
}
export function getLanguage(): Language {
  return localStorage.getItem('wasl:language') === 'ar' ? 'ar' : 'en';
}
export function setLanguage(language: Language) {
  localStorage.setItem('wasl:language', language);
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
}
export function formatDate(date: string, lang: Language, withTime = false) {
  return new Intl.DateTimeFormat(lang === 'ar' ? 'ar-EG' : 'en-GB', {
    day: 'numeric',
    month: 'short',
    ...(withTime ? ({ hour: '2-digit', minute: '2-digit' } as const) : {}),
  }).format(new Date(date));
}
export function initials(name: string) {
  return name
    .trim()
    .split(/\s+/)
    .slice(0, 2)
    .map((s) => s[0])
    .join('')
    .toUpperCase();
}
export function activityKey(action: string): TranslationKey {
  const map: Record<string, TranslationKey> = {
    reply: 'replyEvent',
    claim: 'claimEvent',
    assign: 'assignEvent',
    reopen: 'reopenEvent',
    resolve: 'resolveEvent',
    in_progress: 'in_progressEvent',
    waiting_customer: 'waiting_customerEvent',
    urgency: 'urgencyEvent',
  };
  return map[action] || (action in en ? (action as TranslationKey) : 'updateSuccess');
}
export function errorKey(error: unknown): TranslationKey {
  const e = error as { message?: string; code?: string; status?: number };
  const message = e?.message || String(error);
  if (e?.code === 'same_password') return 'errorSamePassword';
  if (e?.code === 'weak_password') return 'errorWeakPassword';
  if (
    e?.code === 'email_address_invalid' ||
    (e?.code === 'validation_failed' && message.toLowerCase().includes('email'))
  )
    return 'errorEmail';
  if (e?.code === 'over_email_send_rate_limit' || e?.code === 'over_request_rate_limit')
    return 'errorRate';
  if (message.toLowerCase().includes('error sending recovery email')) return 'errorEmailDelivery';
  const pairs: [string, TranslationKey][] = [
    ['RECOVERY_SIGNOUT_FAILED', 'errorRecoverySignout'],
    ['RECOVERY_INVALID', 'recoveryInvalid'],
    ['PASSWORD_MISMATCH', 'errorPasswordMismatch'],
    ['INVALID_EMAIL', 'errorEmail'],
    ['PROFILE_MISSING', 'errorProfileMissing'],
    ['CONFLICT', 'errorConflict'],
    ['FORBIDDEN', 'errorForbidden'],
    ['NOT_OWNER', 'errorOwner'],
    ['INVALID_STATE', 'errorState'],
    ['REQUEST_CLOSED', 'errorClosed'],
    ['INVALID_TITLE', 'errorTitle'],
    ['INVALID_DESCRIPTION', 'errorDescription'],
    ['INVALID_MESSAGE', 'errorMessage'],
    ['RESOLUTION_REQUIRED', 'errorResolution'],
    ['FILE_SIZE', 'errorFileSize'],
    ['INVALID_FILE', 'errorFileType'],
    ['FILE_NAME', 'errorFileName'],
    ['ATTACHMENT_LIMIT', 'errorFileLimit'],
    ['Invalid login', 'errorAuth'],
    ['Email not confirmed', 'errorAuth'],
    ['INVALID_PASSWORD', 'errorPassword'],
    ['INVALID_NAME', 'errorName'],
    ['SESSION_EXPIRED', 'errorSession'],
    ['UPLOAD_FAILED', 'attachmentFailure'],
  ];
  for (const [part, key] of pairs) if (message.includes(part)) return key;
  if (e?.status === 429) return 'errorRate';
  if (['42P01', 'PGRST205', 'PGRST202'].includes(e?.code || '')) return 'errorSetup';
  return 'errorGeneric';
}
